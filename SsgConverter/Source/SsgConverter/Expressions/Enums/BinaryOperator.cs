namespace Ecl.SsgConverter.Expressions {

  /// <summary>
  /// A binary operator.
  /// </summary>
  public enum BinaryOperator {

    /// <summary>
    /// Logical AND (AND).
    /// </summary>
    And,

    /// <summary>
    /// Logical OR (OR).
    /// </summary>
    Or,

    /// <summary>
    /// Logical XOR (XOR).
    /// </summary>
    Xor,

    /// <summary>
    /// Plus (+).
    /// </summary>
    Plus,

    /// <summary>
    /// Minus (-).
    /// </summary>
    Minus,

    /// <summary>
    /// Greater than (>).
    /// </summary>
    GreaterThan,

    /// <summary>
    /// Greater than or equal to (>=).
    /// </summary>
    GreaterThanOrEqualTo,

    /// <summary>
    /// Unequality (<>).
    /// </summary>
    UnequalTo,

    /// <summary>
    /// Equality (=).
    /// </summary>
    EqualTo,

    /// <summary>
    /// Less than or equal to (<=).
    /// </summary>
    LessThanOrEqualTo,

    /// <summary>
    /// Less than (<).
    /// </summary>
    LessThan
  }
} // namespace Ecl.SsgConverter.Expressions
