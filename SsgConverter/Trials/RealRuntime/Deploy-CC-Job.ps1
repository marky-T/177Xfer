<#
  Deploy-CC-Job.ps1  —  Area D, Stage B deployment

  Wraps an SsgConverter body-only report (Examples\Output\<Program>.ps1) in the AMT Control Center
  job skeleton (imports + Set-Jobname + Initialize + Try/Fin/Catch/Finally) and deploys it into the
  live Federale Scripts tree so it can be registered as a Control Center job (Type = Script).

  Writes into E:\Repos\Federale_InternalRelease\Scripts\<Group>\RUN\<Program>.ps1 and, if missing,
  creates Scripts\Settings\AmtSettings.xml from the trial's Trials\RealRuntime\AmtSettings.xml.
  Idempotent: re-running overwrites the deployed script; the settings file is created only if absent.

  Guardrails: our own isolated AMT177 VM. Does not modify R&D scripts; only adds our <Group> folder
  and (if absent) the shared Settings\AmtSettings.xml. The Libraries\ siblings already exist.
#>
[CmdletBinding()]
param(
  [string]$Program = 'CFH-COPY',
  [string]$Group   = 'SSGTRIAL',
  [string[]]$JobParameters = @('80'),
  [string[]]$SgsSeed = @('INPUT ECL-TAPEIN,80,1', 'OUTPUT ECL-TAPEOUT,80,1', 'ASCII 1'),
  [string]$ScriptsRoot = 'E:\Repos\Federale_InternalRelease\Scripts'
)
$ErrorActionPreference = 'Stop'
$rt = $PSScriptRoot

$src = Join-Path (Split-Path (Split-Path $rt -Parent) -Parent) "Examples\Output\$Program.ps1"
if (-not (Test-Path $src)) { throw "Converter output not found: $src" }

# 1) Settings sibling (shared) — create from the trial settings only if it doesn't already exist.
$settingsDir  = Join-Path $ScriptsRoot 'Settings'
$settingsFile = Join-Path $settingsDir 'AmtSettings.xml'
if (-not (Test-Path $settingsFile)) {
  Copy-Item (Join-Path $rt 'AmtSettings.xml') $settingsFile -Force
  Write-Host "Created $settingsFile"
} else {
  Write-Host "Settings already present: $settingsFile"
}

# 2) Target folder Scripts\<Group>\RUN\
$dstDir = Join-Path $ScriptsRoot "$Group\RUN"
New-Item -ItemType Directory -Force -Path $dstDir | Out-Null
$dst = Join-Path $dstDir "$Program.ps1"

# 3) Body = converter output minus its top-level `param(...)` line (lowercase, column 0 only;
#    Define_filer's indented `Param(` is preserved).
$lines = Get-Content $src
$removed = $false
$body = $lines | Where-Object {
  if (-not $removed -and $_ -cmatch '^param\(') { $removed = $true; $false } else { $true }
}

# 4) Compose the CC job skeleton around the body (body ends in its own `Fin`).
$seed = ($SgsSeed | ForEach-Object { "  AddTo-SgsList `"$_`"" }) -join "`r`n"
$plist = ($JobParameters | ForEach-Object { "'$_'" }) -join ','
$header = @"
# $Program wrapped for AMT Control Center (Type: Script) - generated by Deploy-CC-Job.ps1
# Body: SsgConverter Examples\Output\$Program.ps1 (unchanged); wrapper adds the AMT job skeleton.
Import-Module -Name "..\..\Libraries\AmtPsEclLib.psm1"  -Force -DisableNameChecking -ErrorAction Stop
Import-Module -Name "..\..\Libraries\AmtPsSortLib.psm1" -Force -DisableNameChecking -ErrorAction Stop
`$AmtSettingsFile = "..\..\Settings\AmtSettings.xml"

Set-Jobname "$Program"
Initialize `$AmtSettingsFile
Try {
  `$Parameters = @($plist)
  if (-not `$global:SgsLabels) { `$global:SgsLabels = New-Object 'System.Collections.Generic.Dictionary[String, Object]' }
$seed
"@
$footer = @"
} Catch [Exception] {
  HandleTrapAndAbort "Error trapped: " `$_
} Finally {
  Cleanup `$false
}
"@
$out = $header + "`r`n" + ($body -join "`r`n") + "`r`n" + $footer
Set-Content -Path $dst -Value $out -Encoding UTF8
Write-Host "Deployed $dst  ($(($out -split "`n").Count) lines)"
