-- Read-only check for EUU003's tables (MT-069, plan 261116 step E4). SELECTs only.
-- Run elevated/with DB access:  sqlcmd -S VMFEDPE08 -d FA_AFBUS -E -C -i Check-Eu001.sql -o Check-Eu001.out.txt -W -s"|"
SET NOCOUNT ON;

SELECT TABLE_SCHEMA, TABLE_NAME
FROM INFORMATION_SCHEMA.TABLES
WHERE TABLE_NAME IN ('EU001', 'EU002');

SELECT TABLE_SCHEMA, TABLE_NAME, COLUMN_NAME, DATA_TYPE, CHARACTER_MAXIMUM_LENGTH, NUMERIC_PRECISION, NUMERIC_SCALE
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_NAME IN ('EU001', 'EU002')
ORDER BY TABLE_SCHEMA, TABLE_NAME, ORDINAL_POSITION;

DECLARE @s nvarchar(128), @sql nvarchar(max);
SELECT TOP 1 @s = TABLE_SCHEMA FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_NAME = 'EU001';
IF @s IS NOT NULL
BEGIN
  SET @sql = N'SELECT COUNT(*) AS EU001_ROWS FROM ' + QUOTENAME(@s) + N'.EU001;'
           + N'SELECT TOP 5 * FROM ' + QUOTENAME(@s) + N'.EU001 WHERE K_CLE_TAB = ''1'';';
  EXEC sp_executesql @sql;
END

SET @s = NULL;
SELECT TOP 1 @s = TABLE_SCHEMA FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_NAME = 'EU002';
IF @s IS NOT NULL
BEGIN
  SET @sql = N'SELECT COUNT(*) AS EU002_ROWS FROM ' + QUOTENAME(@s) + N'.EU002;'
           + N'SELECT TOP 10 * FROM ' + QUOTENAME(@s) + N'.EU002;';
  EXEC sp_executesql @sql;
END
